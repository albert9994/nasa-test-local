// Engine adapter over the Rust engine compiled to WebAssembly (crates/fieldshift-wasm, built by `pnpm wasm` /
// wasm-pack into packages/engine-wasm). Same `Engine` interface as the TS mock, so the UI never knows which one answers.
//
// The module is loaded with a dynamic `import()` (own chunk, only fetched when used) and initialised once. The relative
// path and the `new URL(..., import.meta.url)` below are resolved by both Next (Turbopack) and Vite.
import type {
  CropValidation, Engine, FarmHandle, ObservedYields, Opts, QuantParams, QuantResult, Rotation,
} from "./types";
import { loadQuantParams } from "./quant-params";

/** The wasm-bindgen exports we use (names are the `js_name`s of crates/fieldshift-wasm). */
interface WasmModule {
  default(input?: { module_or_path: unknown } | unknown): Promise<unknown>;
  prepareFarm(pack: unknown): number;
  releaseFarm(handle: number): void;
  simulateSeason(h: number, crop: string, year: number, opts: unknown, trace?: boolean): unknown;
  simulateRotation(h: number, rot: unknown, opts: unknown, traceYear?: number): unknown;
  adaptationMargin(h: number, rot: unknown, opts: unknown): unknown;
  frontier(h: number, rot: unknown, opts: unknown): unknown;
  optimize(h: number, pool: unknown, opts: unknown, w: unknown, baseline: unknown, c: unknown): unknown;
  pickThree(ranked: unknown, baseline: unknown): unknown;
  marginYear(h: number, rot: unknown, opts: unknown, series: unknown): unknown;
  marketShock(h: number, rot: unknown, opts: unknown, shock: unknown): unknown;
  quantSimulate(h: number, rots: unknown, opts: unknown, params: unknown, quantParams?: unknown): unknown;
  factSheet(h: number, rot: unknown, opts: unknown, picks: unknown, constraints?: unknown): unknown;
  validate(h: number, observed: unknown, opts?: unknown): unknown;
  score?(h: number, rot: unknown, opts: unknown, w?: unknown, c?: unknown, llm?: unknown): unknown;
}

let loading: Promise<WasmModule> | null = null;

/** Loads and initialises the module once. `source` (bytes or URL) overrides the bundled `.wasm` (used by tests). */
export function loadWasmModule(source?: unknown): Promise<WasmModule> {
  if (!loading) {
    loading = (async () => {
      // @ts-ignore: generated by `wasm-pack build` (packages/engine-wasm is git-ignored); typed by WasmModule above
      const mod = (await import("../../../../engine-wasm/fieldshift_wasm.js")) as unknown as WasmModule;
      await mod.default({
        module_or_path: source ?? new URL("../../../../engine-wasm/fieldshift_wasm_bg.wasm", import.meta.url),
      });
      return mod;
    })();
    loading.catch(() => { loading = null; });
  }
  return loading;
}

const toRust = (h: FarmHandle) => Number(h);

/** The `Engine` backed by the Rust WASM build. Rejects if the module cannot be loaded. */
export async function createWasmEngine(source?: unknown): Promise<Engine> {
  const m = await loadWasmModule(source);
  // smoke test: fail now (and let the caller fall back to the mock) rather than on the first user action
  if (typeof m.prepareFarm !== "function") throw new Error("engine-wasm: unexpected module shape");
  return {
    kind: "wasm",
    async prepareFarm(pack) { return String(m.prepareFarm(pack)); },
    async simulateSeason(h, crop, year, opts, trace = false) {
      return m.simulateSeason(toRust(h), crop, year, opts, trace) as never;
    },
    async simulateRotation(h, rot, opts, traceYear) {
      return m.simulateRotation(toRust(h), rot, opts, traceYear ?? undefined) as never;
    },
    async adaptationMargin(h, rot, opts) { return m.adaptationMargin(toRust(h), rot, opts) as never; },
    async frontier(h, rot, opts) { return m.frontier(toRust(h), rot, opts) as never; },
    async optimize(h, pool, opts, w, baseline, c) { return m.optimize(toRust(h), pool, opts, w, baseline, c) as never; },
    async pickThree(ranked, baseline) { return m.pickThree(ranked, baseline) as never; },
    async marginYear(h, rot, opts, series) { return m.marginYear(toRust(h), rot, opts, series) as never; },
    async marketShock(h, rot, opts, shock) { return m.marketShock(toRust(h), rot, opts, shock) as never; },
    async quantSimulate(h: FarmHandle, rots: Rotation[], opts: Opts, p: QuantParams, qp?: unknown): Promise<QuantResult[]> {
      return m.quantSimulate(toRust(h), rots, opts, p, qp ?? (await loadQuantParams())) as never;
    },
    async factSheet(h, rot, opts, picks) { return m.factSheet(toRust(h), rot, opts, picks, undefined) as never; },
    async validate(h: FarmHandle, observed: ObservedYields, opts?: Opts): Promise<Record<string, CropValidation>> {
      return m.validate(toRust(h), observed, opts) as never;
    },
  };
}
