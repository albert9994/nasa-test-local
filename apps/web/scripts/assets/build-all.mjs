// Builds every generated asset for the site: `pnpm --filter web assets`
//   public/models/*.glb          procedural crops (corn, corn-lod, wheat, soybean)
//   public/models/climate-*.glb  "climate ridge": 25 years × 73 five-day steps of NASA POWER Tmax as a 3D landscape
//   public/brand/*.svg, public/bg/*.svg, public/icons/*.svg
// The NASA imagery in public/textures and public/images is downloaded by fetch-nasa.sh (public domain, NASA GIBS).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as THREE from "three";
import { writeGLB } from "./glb.mjs";
import { buildModels } from "./models.mjs";
import { buildSvgs } from "./svgs.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../public");
for (const d of ["models", "brand", "bg", "icons"]) mkdirSync(join(root, d), { recursive: true });

const report = buildModels(join(root, "models"));

// ---- climate ridge from a real farm pack ----
const heat = [[0, "#2b3a55"], [0.35, "#3f6b24"], [0.6, "#e8b64c"], [0.8, "#ef6a4c"], [1, "#fff1d6"]].map(([t, c]) => [t, new THREE.Color(c)]);
const ramp = (t) => {
  for (let i = 1; i < heat.length; i++) if (t <= heat[i][0]) {
    const [a, ca] = heat[i - 1], [b, cb] = heat[i];
    return ca.clone().lerp(cb, (t - a) / (b - a));
  }
  return heat[heat.length - 1][1].clone();
};
for (const id of ["iowa", "kansas", "baragan"]) {
  const pack = JSON.parse(readFileSync(join(root, "data/mock/farms", `${id}.json`), "utf8"));
  const years = Object.keys(pack.weather).sort();
  const steps = 73, W = 6, D = 3.2, H = 1.1;
  const rows = years.map((y) => {
    const t = pack.weather[y].tmax;
    const raw = Array.from({ length: steps }, (_, s) => { let sum = 0, n = 0; for (let d = s * 5; d < Math.min(t.length, s * 5 + 5); d++) { sum += t[d]; n++; } return sum / n; });
    return raw.map((v, s) => (raw[Math.max(0, s - 1)] + 2 * v + raw[Math.min(steps - 1, s + 1)]) / 4); // light smoothing
  });
  const lo = -15, hi = 38;
  const g = new THREE.PlaneGeometry(W, D, steps - 1, years.length - 1);
  g.rotateX(-Math.PI / 2);
  const pos = g.attributes.position, col = new Float32Array(pos.count * 3);
  for (let r = 0; r < years.length; r++) for (let s = 0; s < steps; s++) {
    const i = r * steps + s, v = Math.max(0, Math.min(1, (rows[r][s] - lo) / (hi - lo)));
    pos.setY(i, v * v * H);
    const c = ramp(v);
    col.set([c.r, c.g, c.b], i * 3);
  }
  g.setAttribute("color", new THREE.BufferAttribute(col, 3));
  g.deleteAttribute("uv");
  g.computeVertexNormals();
  // year rows run from 2001 (back) to 2025 (front); extras let the page label them
  report[`climate-${id}.glb`] = writeGLB(join(root, "models", `climate-${id}.glb`),
    [{ name: "ridge", geometry: g, material: { roughness: 0.55 } }],
    { farm: id, years: years.map(Number), steps, tmaxRange: [lo, hi], size: [W, D, H] });
}

Object.assign(report, buildSvgs(root));
writeFileSync(join(root, "models/README.txt"),
  "Generated by apps/web/scripts/assets/build-all.mjs (procedural; climate-*.glb from NASA POWER daily Tmax 2001–2025).\n");
for (const [k, v] of Object.entries(report)) console.log(k.padEnd(28), typeof v === "number" ? `${(v / 1024).toFixed(1)} KB` : v);
