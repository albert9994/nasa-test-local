def compute_soil_taw(pack: dict[str, Any]) -> float:
    """Estimate root-zone plant-available water (mm) from SoilGrids sand & clay."""
    soil = pack.get("soil", {})

    def _mean_prop(prop: str) -> float | None:
        layer = soil.get(prop, {})
        vals = [
            float(v["mean"])
            for v in layer.values()
            if isinstance(v, dict) and "mean" in v
        ]
        return sum(vals) / len(vals) if vals else None

    sand = _mean_prop("sand")
    clay = _mean_prop("clay")
    if sand is None or clay is None:
        return 170.0
    taw = 200.0 - (sand - 30.0) * 1.6 + (-15.0 if clay > 40.0 else 0.0)
    return float(max(90.0, min(230.0, taw)))


def simulate_crop_season(
    pack: dict[str, Any],
    crop: str,
    year: int,
    taw: float,
) -> tuple[float, float] | None:
    """Run FAO-56 daily soil-water & heat-stress screening simulation for (crop, year).

    Returns `(uncalibrated_yield_t_ha, water_x_heat_factor)`.
    """
    spec = CROP_SPECS[crop]
    sow = int(spec["sow"])
    length = int(spec["len"])
    start_year = year - 1 if sow < 0 else year
    weather = pack.get("weather", {})
    w0 = weather.get(str(start_year)) or weather.get(str(year))
    w1 = weather.get(str(year))
    if not w0 or not w1:
        return None

    if sow < 0:
        sow = len(w0["tmax"]) + sow

    # Deep root + subsoil store capacity (Albert's A7 recipe: roots + subsoil store)
    cap = taw * float(spec["root_mult"]) * 1.35
    sow_idx = min(max(0, sow), len(w0["tmax"]) - 1)
    gwet_sow = w0.get("gwet", [0.5] * len(w0["tmax"]))[sow_idx]
    # Include spring pre-sowing recharge for spring-sown crops
    pre_rain = sum(float(w1["prcp"][d]) for d in range(max(0, sow_idx - 60), sow_idx)) if sow > 0 else 0.0
    s = min(cap, cap * (0.55 + 0.40 * float(gwet_sow)) + 0.35 * pre_rain)

    stage_et = [0.0, 0.0, 0.0, 0.0]
    stage_eta = [0.0, 0.0, 0.0, 0.0]
    heat_days = 0
    edd = 0.0
    frost_hits = 0

    fl_start, fl_end = spec["flower"]
    kc_ini, kc_mid, kc_end = spec["kc"]
    heat_t = float(spec["heat_t"])

    for i in range(length):
        d = sow + i
        w = w0
        if w0 is not w1 and d >= len(w0["tmax"]):
            d -= len(w0["tmax"])
            w = w1
        d = min(d, len(w["tmax"]) - 1)

        tmax = float(w["tmax"][d])
        tmin = float(w["tmin"][d])
        prcp = float(w["prcp"][d])
        rad = float(w.get("rad", [18.0] * len(w["tmax"]))[d])
        gwet = float(w.get("gwet", [0.5] * len(w["tmax"]))[d])

        fr = i / length
        stage = 0 if fr < fl_start else (1 if fr < fl_end else (2 if fr < 0.85 else 3))
        kc = kc_ini if fr < 0.2 else (kc_mid if fr < 0.75 else kc_end)
        tmean = 0.5 * (tmax + tmin)
        et0 = max(0.0, 0.0135 * (tmean + 17.8) * (rad / 2.45))
        etc = kc * et0
        ro = (prcp - 30.0) * 0.35 if prcp > 30.0 else 0.0
        s = min(cap, s + prcp - ro)
        ks = min(1.0, (0.55 * (s / (cap * 0.42)) + 0.45 * (gwet / 0.50)))
        eta = etc * ks
        s = max(0.0, s - eta)

        stage_et[stage] += etc
        stage_eta[stage] += eta
        if tmax > heat_t and stage == 1:
            heat_days += 1
        if tmax > 32.5 and stage in (1, 2):
            edd += tmax - 32.5
        if tmin < -3.0 and stage in (1, 2):
            frost_hits += 1

    ky_weights = [0.12 * spec["ky"], 0.42 * spec["ky"], 0.28 * spec["ky"], 0.05 * spec["ky"]]
    water_factor = 1.0
    for st in range(4):
        if stage_et[st] > 0:
            water_factor *= max(0.45, 1.0 - ky_weights[st] * (1.0 - stage_eta[st] / stage_et[st]))

    heat_factor = max(0.55, 1.0 - 0.02 * heat_days) * math.exp(-0.0014 * edd)
    frost_factor = max(0.60, 1.0 - 0.05 * frost_hits)

    # Agronomic technology trend (~1.1%/yr centered on 2012)
    tech_factor = 1.0 + 0.011 * (year - 2012)
    raw_yield = float(spec["y_pot"]) * water_factor * heat_factor * frost_factor * tech_factor
    return raw_yield, water_factor * heat_factor


def load_observed_yields(farm_id: str, validation_dir: Path = VALIDATION_DIR) -> dict[str, dict[int, float]]:
    """Load observed county yields from C5 `validation/<farm>.json` or fallback table."""
    c5_path = validation_dir / f"{farm_id}.json"
    if c5_path.exists():
        try:
            with open(c5_path, encoding="utf-8") as handle:
                data = json.load(handle)
            crops_obj = data.get("crops", {})
            parsed: dict[str, dict[int, float]] = {}
            for crop, info in crops_obj.items():
                years_dict = info.get("years", {})
                parsed[crop] = {int(k): float(v) for k, v in years_dict.items()}
            if parsed:
                return parsed
        except (OSError, ValueError, TypeError, KeyError) as exc:
            print(f"[validate] warning reading {c5_path}: {exc}", file=sys.stderr)
    return OBSERVED_YIELDS_FALLBACK.get(farm_id, {})


def pearson_r(x: list[float], y: list[float]) -> float:
    if len(x) < 2:
        return 0.0
    x_arr = np.asarray(x, dtype=float)
    y_arr = np.asarray(y, dtype=float)
    if np.std(x_arr) < 1e-9 or np.std(y_arr) < 1e-9:
        return 0.0
    return float(np.corrcoef(x_arr, y_arr)[0, 1])


def compute_ndvi_correlation(
    pack: dict[str, Any],
    primary_crop: str,
    taw: float,
) -> dict[str, float | int]:
    """Correlate MODIS growing-season peak NDVI (DOY 110-260) with modelled water x heat factor."""
    ndvi_by_year = pack.get("ndvi", {})
    peaks: list[float] = []
    factors: list[float] = []

    doy_min, doy_max = (80, 175) if primary_crop == "wheat" else (145, 245)

    for y_str, pairs in sorted(ndvi_by_year.items()):
        year = int(y_str)
        if not pairs:
            continue
        gs_vals = [
            float(val)
            for doy, val in pairs
            if val is not None and doy_min <= int(doy) <= doy_max and float(val) > 0.1
        ]
        if not gs_vals:
            continue
        sim = simulate_crop_season(pack, primary_crop, year, taw)
        if sim is None:
            continue
        top_vals = sorted(gs_vals, reverse=True)[:3]
        peaks.append(sum(top_vals) / len(top_vals))
        factors.append(sim[0])

    r_val = pearson_r(peaks, factors)
    return {"n": len(peaks), "r": round(r_val, 2)}


def validate_all_farms(
    *,
    farms_dir: Path = FARMS_DIR,
    layers_dir: Path = LAYERS_DIR,
    validation_dir: Path = VALIDATION_DIR,
) -> dict[str, Any]:
    """Run calibration and validation for all demo farms and write `summary.json` (C6)."""
    farms = load_farms()
    summary: dict[str, Any] = {}

    for farm in farms:
        farm_id = farm["id"]
        pack_path = farms_dir / f"{farm_id}.json"
        if not pack_path.exists():
            continue
        with open(pack_path, encoding="utf-8") as handle:
            pack = json.load(handle)

        taw = compute_soil_taw(pack)
        obs_by_crop = load_observed_yields(farm_id, validation_dir=validation_dir)
        farm_summary: dict[str, Any] = {}
        calib_by_crop: dict[str, float] = {}

        for crop, obs_years in obs_by_crop.items():
            if crop not in CROP_SPECS:
                continue
            years_list: list[int] = []
            obs_list: list[float] = []
            raw_mod_list: list[float] = []

            for year, obs_val in sorted(obs_years.items()):
                sim = simulate_crop_season(pack, crop, year, taw)
                if sim is None:
                    continue
                years_list.append(year)
                obs_list.append(obs_val)
                raw_mod_list.append(sim[0])

            if not years_list:
                continue

            obs_mean = sum(obs_list) / len(obs_list)
            raw_mean = sum(raw_mod_list) / len(raw_mod_list)
            calib = round(obs_mean / raw_mean, 2) if raw_mean > 0 else 1.0
            calib_by_crop[crop] = calib

            mod_list = [round(v * calib, 2) for v in raw_mod_list]
            r_val = pearson_r(obs_list, mod_list)
            rmse_val = math.sqrt(
                sum((m - o) ** 2 for o, m in zip(obs_list, mod_list)) / len(obs_list)
            )
            bias_val = sum(m - o for o, m in zip(obs_list, mod_list)) / len(obs_list)

            pairs = [
                [int(y), round(float(o), 2), round(float(m), 2)]
                for y, o, m in zip(years_list, obs_list, mod_list)
            ]
            farm_summary[crop] = {
                "n": len(pairs),
                "r": round(r_val, 2),
                "rmse": round(rmse_val, 2),
                "bias": round(bias_val, 2),
                "calib": calib,
                "pairs": pairs,
            }

        primary_crop = farm.get("rotation", ["maize"])[0]
        if primary_crop not in CROP_SPECS:
            primary_crop = "maize"
        farm_summary["ndvi"] = compute_ndvi_correlation(pack, primary_crop, taw)
        summary[farm_id] = farm_summary

        # Update meta.calib in layers/<farm_id>/meta.json
        meta_path = layers_dir / farm_id / "meta.json"
        if meta_path.exists() and calib_by_crop:
            with open(meta_path, encoding="utf-8") as handle:
                meta = json.load(handle)
            meta["calib"] = calib_by_crop
            atomic_write_json(meta_path, meta, indent=2)

    atomic_write_json(validation_dir / "summary.json", summary, indent=2)
    atomic_write_json(MOCK_DIR / "summary.json", summary, indent=2)
    build_all_packs(layers_dir=layers_dir, farms_dir=farms_dir, seed_mock=False)
    return summary


